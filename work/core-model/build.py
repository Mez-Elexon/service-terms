"""Build the Flexibility Core Model documentation from model.py.

Outputs (next to this script):
  - "Flexibility Core Model.md"   Markdown with ```math (MathJax, as GitHub renders) and Mermaid diagrams
  - "Flexibility Core Model.html" the visual: page.html with the model embedded as JSON

Usage: python3 build.py
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model as M  # noqa: E402
import texlayout as L  # noqa: E402

KIND_LABEL = {"Def": "Def", "Rule": "Rule", "Derived": "Derived", "Open": "Open"}


def math(tex):
    return "```math\n" + L.stacked(tex) + "\n```"


def stmt_refs(ns):
    return ", ".join(str(n) for n in ns)


def coverage():
    return {n: [e["id"] for e in M.EXPRESSIONS if n in e["stmts"]] for n, *_ in M.STATEMENTS}


def build_markdown():
    cov = coverage()
    out = []
    w = out.append
    w(f"# Flexibility Core Model – {M.VERSION}\n")
    w(f"> **Status:** {M.VERSION} for review ({M.DATE}). Not BSC text.  ")
    w("> **What it is:** the 99 consolidated statements (CAA relationships, the BSC Site Configuration proposal and the control layer) written as a core set of expressions, in notation aligned with BSC Annex X-2.  ")
    w("> **Companion:** `Flexibility Core Model.html` shows the same model visually, with an interactive metering-tree explorer and a differencing timeline.  ")
    w("> **Source of truth:** `model.py`. Both files are generated by `build.py`; edit `model.py` and rebuild rather than editing this file.  ")
    w("> **Earlier work:** supersedes `work/Flexibility Asset Notation - Draft v0.2.md` for these statements; v0.2 stays as the record of the earlier statement set.\n")
    w("---\n")

    w("## Choices behind the model\n")
    for i, c in enumerate(M.CHOICES, 1):
        w(f"{i}. {c}")
    w("")

    w("## How to read the notation\n")
    w("The notation follows Annex X-2 where the BSC already has a symbol, and adds a few devices to make the structure easier to read:\n")
    w("- **BSC symbols are kept** where they exist: K for a metering identity (Table X-4), j for a Settlement Period, i2 for a Secondary BM Unit, p for a party, `[P]` as a 1/0 indicator, Σ and ∈ as in paragraphs 1.2 and 2.6. Volumes use the BSC's run-together form, e.g. $`QM_{Kj}`$.")
    w("- **Relations are named functions you can read aloud.** $`\\operatorname{reach}_t(K)`$ is “the reach of K at t”; $`\\operatorname{per}_t(x)`$ is “the perimeter of x”; $`\\operatorname{grp}(a)`$ is “the group of a”.")
    w("- **The three arrangement types are written as constructors:** $`\\mathrm{Bnd}`$, $`\\mathrm{Ast}(A)`$ and $`\\mathrm{Res}(X)`$, where X is the set of AMSID Pairs subtracted.")
    w("- **The metering tree has its own symbol:** $`A \\sqsubset A'`$ means A sits behind A′; the root $`\\top_c`$ is the boundary.")
    w("- **Every record carries an interval** $`I(e)`$, and $`\\operatorname{live}_t(e)`$ says it is in force at t. That is how every statement is indexed by time.")
    w("- **Records use Greek letters:** φ a CFPC, δ a delegation, κ a registration (claim), λ an allocation, π a participation.")
    w("- **Each expression has an ID**: D for definitions, E for rules and derived results, V for volumes, O for open items and objectives. The statement numbers it covers are listed under it.\n")

    w("## The model at a glance\n")
    w("```mermaid")
    w("flowchart LR")
    w("  subgraph measure[Measurement]")
    w("    BP[Boundary Point b] --- MP[MSID Pair M_b]")
    w("    SC[Site Configuration c] -->|root| MP")
    w("    SC -->|nests| AP[AMSID Pairs A]")
    w("    AP -->|Asset Meter Allocation| AM[Asset Meter m]")
    w("    SITE[Site w] -.groups.-> SC")
    w("  end")
    w("  subgraph control[Control]")
    w("    TR[TRs r] -->|behind| BP")
    w("    TR --> CG[Control groups g]")
    w("    TR --> RG[Residual group R]")
    w("    CG -->|one| LC[Load Controller]")
    w("  end")
    w("  subgraph asset[Assets]")
    w("    AS[Asset a = g, x] --> CG")
    w("    AS --> AR[Arrangement x: Bnd, Ast, Res]")
    w("    AR --> SC")
    w("  end")
    w("  subgraph who[Who]")
    w("    CFPC[CFPC φ] --> DEL[Delegation δ]")
    w("    CFPC --> REG[Registration κ]")
    w("    DEL --> REG")
    w("    REG --> ALLOC[Allocation λ to the group]")
    w("    ALLOC --> PART[Participation π]")
    w("    DEL -.-> PART")
    w("    PART --> UNIT[Unit u / Secondary BM Unit i2]")
    w("  end")
    w("  ALLOC --> CG")
    w("  PART --> AS")
    w("```\n")

    w("## The core on one page\n")
    w("These expressions carry the structure. Everything else in the model is detail on top of them.\n")
    for e in [e for e in M.EXPRESSIONS if e["core"]]:
        w(f"**{e['id']} · {e['name']}** [{e['kind']}] · statements {stmt_refs(e['stmts'])}\n")
        w(math(e["tex"]) + "\n")
        if e["note"]:
            w(f"{e['note']}\n")

    w("## Notation register\n")
    w("| Symbol | Reads as | BSC alignment |")
    w("|---|---|---|")
    for sym, reads, bsc in M.NOTATION:
        w(f"| $`{sym}`$ | {reads} | {bsc} |")
    w("")

    w("## The statements, section by section\n")
    for sec, title in M.SECTIONS.items():
        w(f"### {sec}. {title}\n")
        w("| # | Tag | Statement | Expressions |")
        w("|---|---|---|---|")
        for n, tag, s, text in M.STATEMENTS:
            if s == sec:
                w(f"| {n} | {tag} | {text} | {', '.join(cov[n])} |")
        w("")
        for e in [e for e in M.EXPRESSIONS if e["sec"] == sec]:
            w(f"**{e['id']} · {e['name']}** [{e['kind']}] · statements {stmt_refs(e['stmts'])}\n")
            w(math(e["tex"]) + "\n")
            if e["note"]:
                w(f"{e['note']}\n")
        if sec == 3:
            w("Example metering tree (the one used in the HTML explorer):\n")
            w("```mermaid")
            w("flowchart TD")
            w("  T[\"⊤ Boundary: MSID Pair\"] --> A1[\"A1 Garage sub-board\"]")
            w("  T --> A3[\"A3 Battery inverter\"]")
            w("  A1 --> A2[\"A2 EV charger\"]")
            w("```\n")
            w("Here A2 ⊏ A1, while A1 and A3 sit side by side, so their reaches are disjoint (E18).\n")
        if sec == 10:
            w("```mermaid")
            w("flowchart LR")
            w("  PA[AMSID Pairs participating in j] --> OUT[Keep the outermost: no participating ancestor]")
            w("  OUT --> SUB[QSUB = sum of their volumes]")
            w("  SUB --> RES[QRES = QM of MSID Pair − QSUB]")
            w("  PA -->|any at all?| DIFF[DIFF flag for j]")
            w("  DIFF -->|changed by another party| N[Notify MSID Pair participant: P0309 / P0320]")
            w("```\n")

    w("## Findings from formalising\n")
    w("| # | Statements | Finding | Suggested resolution |")
    w("|---|---|---|---|")
    for fid, sts, text, fix in M.FINDINGS:
        w(f"| {fid} | {stmt_refs(sts)} | {text} | {fix} |")
    w("")

    w("## Still open\n")
    for s in M.STILL_OPEN:
        w(f"- {s}")
    w("- The [Open] statements are written out as labelled branches: O67 (multi-group Asset), O70 (CFPC exclusivity) and O77 (competition across sub-markets).\n")

    w("## Statement index\n")
    w("| # | Tag | Section | Expressions |")
    w("|---|---|---|---|")
    for n, tag, s, _ in M.STATEMENTS:
        w(f"| {n} | {tag} | {s}. {M.SECTIONS[s]} | {', '.join(cov[n])} |")
    w("")
    return "\n".join(out)


def build_html():
    data = {
        "version": M.VERSION, "date": M.DATE,
        "sections": M.SECTIONS, "layer": M.LAYER,
        "statements": [dict(n=n, tag=t, sec=s, text=x) for n, t, s, x in M.STATEMENTS],
        "expressions": [dict(e, tex=L.stacked(e["tex"])) for e in M.EXPRESSIONS],
        "notation": [dict(sym=a, reads=b, bsc=c) for a, b, c in M.NOTATION],
        "findings": [dict(id=a, stmts=b, text=c, fix=d) for a, b, c, d in M.FINDINGS],
        "choices": M.CHOICES, "open": M.STILL_OPEN,
    }
    page = open(os.path.join(HERE, "page.html"), encoding="utf-8").read()
    blob = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    assert "/*__MODEL__*/" in page
    return page.replace("/*__MODEL__*/", "window.MODEL = " + blob + ";")


if __name__ == "__main__":
    md = build_markdown()
    with open(os.path.join(HERE, "Flexibility Core Model.md"), "w", encoding="utf-8") as f:
        f.write(md + "\n")
    html = build_html()
    with open(os.path.join(HERE, "Flexibility Core Model.html"), "w", encoding="utf-8") as f:
        f.write(html)
    print("statements", len(M.STATEMENTS), "expressions", len(M.EXPRESSIONS),
          "uncovered", [n for n, v in coverage().items() if not v])
